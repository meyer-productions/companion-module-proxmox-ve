# Builds the full 72x72 button images (badge on top + fixed status band at the bottom) from the badge PNGs
# written by generate-icons.ts, and writes them as base64 into src/button-images.ts.
# Dev-time only (Windows, System.Drawing). The module itself only uses the generated TypeScript file.
# Run via: yarn icons
# Keep this file ASCII only (Windows PowerShell 5.1 reads BOM-less scripts as ANSI).
param(
	[string]$BadgeDir = (Join-Path $PSScriptRoot '..\build\icons'),
	[string]$Target = (Join-Path $PSScriptRoot '..\src\button-images.ts')
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$ellipsis = [string][char]0x2026
$size = 72
$bandHeight = 14
$badgeTop = 3

# Status band texts. Keys are used by the module (see guest-button.ts).
$states = [ordered]@{
	running       = 'RUNNING'
	stopped       = 'STOPPED'
	unknown       = 'UNKNOWN'
	task_start    = 'START' + $ellipsis
	task_shutdown = 'SHUTDOWN' + $ellipsis
	task_reboot   = 'REBOOT' + $ellipsis
	task_stop     = 'STOP' + $ellipsis
}
$badges = @('start', 'shutdown', 'reboot', 'stop', 'server')

function New-ButtonImage([string]$badgeFile, [string]$bandText) {
	$bmp = New-Object System.Drawing.Bitmap $size, $size, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
	$g = [System.Drawing.Graphics]::FromImage($bmp)
	$g.Clear([System.Drawing.Color]::Transparent)
	$g.SmoothingMode = 'AntiAlias'
	$g.InterpolationMode = 'HighQualityBicubic'
	$g.TextRenderingHint = 'AntiAlias'

	$badge = [System.Drawing.Image]::FromFile($badgeFile)
	$g.DrawImage($badge, 0, $badgeTop, $badge.Width, $badge.Height)
	$badge.Dispose()

	# Semi transparent band, so the state color of the button still shows through.
	$band = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(110, 0, 0, 0))
	$g.FillRectangle($band, 0, $size - $bandHeight, $size, $bandHeight)

	$fontSize = 9
	do {
		$font = New-Object System.Drawing.Font('Arial', $fontSize, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
		$measured = $g.MeasureString($bandText, $font)
		if ($measured.Width -le ($size - 4)) { break }
		$fontSize -= 0.5
	} while ($fontSize -gt 6)

	$format = New-Object System.Drawing.StringFormat
	$format.Alignment = 'Center'
	$format.LineAlignment = 'Center'
	$rect = New-Object System.Drawing.RectangleF 0, ($size - $bandHeight), $size, $bandHeight
	$g.DrawString($bandText, $font, [System.Drawing.Brushes]::White, $rect, $format)

	$stream = New-Object System.IO.MemoryStream
	$bmp.Save($stream, [System.Drawing.Imaging.ImageFormat]::Png)
	$g.Dispose(); $bmp.Dispose()
	return [Convert]::ToBase64String($stream.ToArray())
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('// Generated by scripts/generate-buttons.ps1 (yarn icons) - do not edit by hand.')
$lines.Add('// 72x72 PNG: badge on top, fixed status band at the bottom, transparent in between for the name.')
$lines.Add('')
$lines.Add('export const ButtonImages = {')
foreach ($badge in $badges) {
	$lines.Add("`t${badge}: {")
	foreach ($state in $states.Keys) {
		$data = New-ButtonImage (Join-Path $BadgeDir "$badge.png") $states[$state]
		$lines.Add("`t`t${state}: '$data',")
	}
	$lines.Add("`t},")
}
$armed = New-ButtonImage (Join-Path $BadgeDir 'stopArmed.png') 'PRESS AGAIN'
$lines.Add("`tstopArmed: '$armed',")
$lines.Add('} as const')
$lines.Add('')
$lines.Add('export type ButtonBadge = Exclude<keyof typeof ButtonImages, ''stopArmed''>')
$lines.Add('export type ButtonState = keyof (typeof ButtonImages)[ButtonBadge]')
$lines.Add('')

$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $Target)).Path + '\' + (Split-Path $Target -Leaf), ($lines -join "`n"), $utf8)
Write-Output "Wrote $($badges.Count * $states.Count + 1) button images to $Target"
